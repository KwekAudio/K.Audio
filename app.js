let currentTab = 'masomo';
let currentStep = 0;
let selectedOption = "";
let xp = 0;
let rank = "Mzalendo Mwanafunzi";
let messages = [{ sender: 'bot', text: 'Habari! Mimi ni AI Chatbot wa MK360. Niulize swali lolote kuhusu Katiba au Historia ya Muungano.' }];

function renderApp() {
  const main = document.getElementById('main-content');
  if (!main) return;
  
  document.getElementById('xp-display').innerText = `⭐ ${xp} XP`;
  document.getElementById('rank-display').innerText = `🎖️ ${rank}`;

  if (currentTab === 'masomo') {
    const data = MK360_CURRICULUM[currentStep];
    main.innerHTML = `
      <div class="fade-in">
        <span class="tag">${data.topic}</span>
        <h2 class="title">${data.title}</h2>
        <div class="info-card">
          <h3>💡 Elimu ya Haraka</h3>
          <p>${data.info}</p>
        </div>
        <div class="quiz-card">
          <p class="question">${data.question}</p>
          <div class="options">
            ${data.options.map(opt => `
              <button class="opt-btn ${selectedOption === opt ? 'selected' : ''}" onclick="selectOpt('${opt}')">${opt}</button>
            `).join('')}
          </div>
          <button class="submit-btn" onclick="submitAnswer()" ${!selectedOption ? 'disabled' : ''}>Tuma Jibu (+50 XP)</button>
        </div>
      </div>`;
  } else if (currentTab === 'ai') {
    main.innerHTML = `
      <div class="chat-container fade-in">
        <div class="chat-box" id="chat-box">
          ${messages.map(m => `<div class="bubble ${m.sender}"><p>${m.text}</p></div>`).join('')}
        </div>
        <div class="input-area">
          <input type="text" id="chat-input" placeholder="Uliza kuhusu Muungano..." onkeydown="if(event.key==='Enter') sendChat()"/>
          <button onclick="sendChat()">Tuma</button>
        </div>
      </div>`;
    setTimeout(() => { const cb = document.getElementById('chat-box'); if(cb) cb.scrollTop = cb.scrollHeight; }, 50);
  } else if (currentTab === 'top') {
    main.innerHTML = `
      <div class="leaderboard fade-in">
        <h2>🏆 Mbao wa Ushindani Kitaifa</h2>
        <div class="list">
          <div class="row top"><span>🥇 1. Erick David</span><span>950 XP</span></div>
          <div class="row top"><span>🥈 2. Asha Salmin</span><span>800 XP</span></div>
          <div class="row top"><span>🥉 3. Juma Hamis</span><span>750 XP</span></div>
          <div class="row current"><span>Wewe (${rank})</span><span>${xp} XP</span></div>
        </div>
      </div>`;
  }
}

window.selectOpt = (opt) => { selectedOption = opt; renderApp(); };

window.submitAnswer = () => {
  const data = MK360_CURRICULUM[currentStep];
  if (selectedOption === data.correct) {
    xp += 50;
    if (xp >= 150 && xp < 400) rank = "Balozi wa Historia";
    if (xp >= 400) rank = "Mlinda Urithi VIP 🎖️";
    alert(`✅ SAHIHI!\n\n${data.feedback}`);
    if (currentStep < MK360_CURRICULUM.length - 1) {
      currentStep++;
      selectedOption = "";
    } else {
      alert("🎉 HONGERA SANA! Umekamilisha maswali yote 10 ya MK360 na kuwa Mzalendo Aliyethibitishwa!");
    }
  } else {
    alert("❌ UKOMESHA KIDOGO!\n\nSoma muhtasari hapo juu kisha ujaribu tena.");
  }
  renderApp();
};

window.sendChat = () => {
  const input = document.getElementById('chat-input');
  if (!input || !input.value.trim()) return;
  const txt = input.value;
  messages.push({ sender: 'user', text: txt });
  renderApp();

  setTimeout(() => {
    let reply = "Swali lako ni zuri sana. Mfumo wa MK360 unalipitisha kwa wanahistoria wetu ili kupata jibu sahihi lililothibitishwa kikatiba.";
    const lowQuery = txt.toLowerCase();
    if (lowQuery.includes("waasisi") || lowQuery.includes("nyerere") || lowQuery.includes("karume")) {
      reply = "Waasisi wa Jamhuri ya Muungano wa Tanzania ni Mwalimu Julius Kambarage Nyerere na Sheikh Abeid Amani Karume, waliounganisha nchi hizi mbili Aprili 26, 1964.";
    } else if (lowQuery.includes("mkataba") || lowQuery.includes("tarehe")) {
      reply = "Mkataba wa Muungano (Articles of Union) ulisainiwa tarehe 22 Aprili 1964 kabla ya kupitishwa rasmi na Bunge la Tanganyika na Baraza la Mapinduzi Zanzibar.";
    } else if (lowQuery.includes("udongo")) {
      reply = "Kuchanganya udongo tarehe 26 Aprili 1964 kulikuwa ni ishara ya kudumu ya kuashiria kwamba pande hizi mbili zimeungana kiundugu na hazitatengana kamwe.";
    }
    messages.push({ sender: 'bot', text: reply });
    renderApp();
  }, 700);
};

window.switchTab = (tab) => {
  currentTab = tab;
  document.querySelectorAll('.nav-btn').forEach((b) => {
    b.classList.remove('active');
  });
  renderApp();
};

document.addEventListener("DOMContentLoaded", renderApp);
